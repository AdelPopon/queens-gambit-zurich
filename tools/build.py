def sitemap(lastmod):
    pairs = [("en/", "", "weekly", "1.0"),
             ("en/impressum/", "impressum/", "yearly", "0.3"),
             ("en/privacy/", "datenschutz/", "yearly", "0.3"),
             ("en/winz/", "winz/", "weekly", "0.8")]
    rows = []
    for en, de, freq, prio in pairs:
        for loc in (de, en):
            rows.append(f"""  <url>
    <loc>{SITE}/{loc}</loc>
    <xhtml:link rel="alternate" hreflang="en" href="{SITE}/{en}"/>
    <xhtml:link rel="alternate" hreflang="de" href="{SITE}/{de}"/>
    <xhtml:link rel="alternate" hreflang="x-default" href="{SITE}/{de}"/>
    <lastmod>{lastmod}</lastmod>
    <changefreq>{freq}</changefreq>
    <priority>{prio}</priority>
  </url>""")
    (ROOT / "sitemap.xml").write_text('<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n'
        + "\n".join(rows) + "\n</urlset>\n")



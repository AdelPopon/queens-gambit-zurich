/* ==========================================================================
   Queen's Gambit Zürich · QGZ Kids Parent Price Calculator
   Page: /kids/eltern/ (DE) and /en/kids/parents/ (EN), generated by
   tools/build.py from tools/kids_parents.html. Styles: css/kids-schools.css.

   Pricing (per lesson, per child):
     base CHF 25.00
     full school year paid in advance: × 0.90
     second and each further child of the same family: × 0.95
     (discounts multiplied: 25.00 / 22.50 / 23.75 / 21.375)
   Child total = price per lesson × scheduled lessons; family total = sum.
   Calculated exactly in ten-thousandths of a franc; amounts are rounded only
   for display, the payable family total to CHF 0.05. Nothing is sent or stored.
   ========================================================================== */
(function (root) {
  "use strict";

  var MIN_LESSONS = 1, MAX_LESSONS = 45, DEFAULT_LESSONS = 12;
  var MIN_KIDS = 1, MAX_KIDS = 5;
  var U = 10000;                       // 1 franc = 10'000 units
  var BASE = 25 * U;

  function toCentimes(units) { return Math.floor((units + 50) / 100); }
  function toFiveRappen(units) { return Math.floor((units + 250) / 500) * 5; }   // in centimes

  // Price per lesson in units: 250000 × (0.90 if yearly) × (0.95 if sibling)
  function lessonUnits(sibling, yearly) {
    var p = BASE;
    if (yearly) p = p * 90 / 100;
    if (sibling) p = p * 95 / 100;
    return p;                          // exact: 250000, 225000, 237500, 213750
  }

  function family(lessons, kids, yearly) {
    var children = [], exact = 0;
    for (var i = 0; i < kids; i++) {
      var per = lessonUnits(i > 0, yearly), tot = per * lessons;
      exact += tot;
      children.push({ perLesson: toCentimes(per), total: toCentimes(tot), exact: tot / U });
    }
    return { children: children, exact: exact / U, payable: toFiveRappen(exact) };
  }

  function calculate(lessons, kids, yearly) {
    var f = family(lessons, kids, yearly);
    var full = BASE * lessons * kids;                       // no discounts
    var r = {
      lessons: lessons, kids: kids, yearly: yearly,
      children: f.children, exactTotal: f.exact, total: f.payable,
      fullPrice: toFiveRappen(full)
    };
    r.saved = r.fullPrice - r.total;
    if (!yearly) {                                          // incentive: same lessons paid yearly
      var y = family(lessons, kids, true);
      r.yearlyTotal = y.payable; r.yearlySaving = r.total - y.payable;
    }
    return r;
  }

  function chf(centimes) {
    var francs = String(Math.floor(centimes / 100)).replace(/\B(?=(\d{3})+(?!\d))/g, "’");
    var rest = String(centimes % 100);
    return "CHF " + francs + "." + (rest.length < 2 ? "0" + rest : rest);
  }

  var API = { calculate: calculate, chf: chf };
  if (typeof module !== "undefined" && module.exports) { module.exports = API; return; }

  /* ---------- Page ---------- */
  var box = document.querySelector("[data-kpp]");
  if (!box) return;
  var msgs = {};
  var tpl = box.querySelector("template[data-kpp-messages]");
  if (tpl) [].forEach.call(tpl.content.querySelectorAll("[data-msg]"), function (el) { msgs[el.getAttribute("data-msg")] = el.textContent; });
  function M(key, vars) {
    return (msgs[key] || "").replace(/\{(\w+)\}/g, function (_, k) { return vars && k in vars ? vars[k] : ""; });
  }
  var q = function (sel) { return box.querySelector(sel); };
  var out = function (name) { return q('[data-kpp-out="' + name + '"]'); };
  var lessonsIn = q("[data-kpp-lessons]"), kidsIn = q("[data-kpp-kids]");
  var result = q("[data-kpp-result]"), notice = q("[data-kpp-notice]");
  box.hidden = false;
  q("[data-kpp-form]").addEventListener("submit", function (e) { e.preventDefault(); });

  function readInt(input) { var v = String(input.value).trim(); return /^\d+$/.test(v) ? parseInt(v, 10) : NaN; }
  function yearly() { var c = q('input[name="kpp-pay"]:checked'); return !!c && c.value === "year"; }
  function show(name, on) { var el = q('[data-kpp-show="' + name + '"]'); if (el) el.hidden = !on; }

  function render() {
    var w = readInt(lessonsIn), k = readInt(kidsIn);
    var wOk = w >= MIN_LESSONS && w <= MAX_LESSONS, kOk = k >= MIN_KIDS && k <= MAX_KIDS;
    if (wOk) lessonsIn.removeAttribute("aria-invalid"); else lessonsIn.setAttribute("aria-invalid", "true");
    if (kOk) kidsIn.removeAttribute("aria-invalid"); else kidsIn.setAttribute("aria-invalid", "true");
    var problem = !wOk ? M("lessons") : (!kOk ? M("kids") : "");
    notice.textContent = problem; notice.hidden = !problem;
    result.classList.toggle("is-stale", !!problem);
    if (problem) return;

    var r = calculate(w, k, yearly());
    out("total").textContent = chf(r.total);
    out("summary").textContent = M(r.yearly ? "summaryYear" : "summaryPeriod", { w: w, kids: M(k === 1 ? "kids1" : "kidsN", { k: k }) });
    var list = out("children"); list.innerHTML = "";
    r.children.forEach(function (c, i) {
      var row = document.createElement("div");
      var dt = document.createElement("dt"); dt.textContent = M(i === 0 ? "child1" : "childN", { n: i + 1 });
      var hint = document.createElement("span"); hint.className = "ksp-breakdown__hint";
      hint.textContent = M("perLesson", { price: chf(c.perLesson), w: w });
      dt.appendChild(hint);
      var dd = document.createElement("dd"); dd.textContent = chf(c.total);
      row.appendChild(dt); row.appendChild(dd); list.appendChild(row);
    });
    show("saving", r.saved > 0);
    out("fullPrice").textContent = chf(r.fullPrice);
    out("saved").textContent = chf(r.saved);
    show("incentive", !r.yearly);
    if (!r.yearly) out("incentive").textContent = M("incentive", { total: chf(r.yearlyTotal), saving: chf(r.yearlySaving) });
    remember(w, k, r.yearly);
  }

  // Values travel with the address, so the language switch keeps them
  function remember(w, k, y) {
    var qs = "?lessons=" + w + "&children=" + k + "&pay=" + (y ? "year" : "period");
    try { history.replaceState(null, "", location.pathname + qs + location.hash); } catch (e) {}
    document.querySelectorAll("[data-lang-link]").forEach(function (a) {
      var href = a.getAttribute("href").split("#");
      a.setAttribute("href", href[0].split("?")[0] + qs + (href[1] ? "#" + href[1] : ""));
    });
  }

  var params = new URLSearchParams(location.search);
  var pw = parseInt(params.get("lessons"), 10), pk = parseInt(params.get("children"), 10);
  if (pw >= MIN_LESSONS && pw <= MAX_LESSONS) lessonsIn.value = pw;
  if (pk >= MIN_KIDS && pk <= MAX_KIDS) kidsIn.value = pk;
  if (params.get("pay") === "year") q('input[name="kpp-pay"][value="year"]').checked = true;

  [].forEach.call(box.querySelectorAll("[data-kpp-step]"), function (btn) {
    btn.addEventListener("click", function () {
      var spec = btn.getAttribute("data-kpp-step").split(":"), d = spec[1] === "+" ? 1 : -1;
      var input = spec[0] === "lessons" ? lessonsIn : kidsIn;
      var min = spec[0] === "lessons" ? MIN_LESSONS : MIN_KIDS, max = spec[0] === "lessons" ? MAX_LESSONS : MAX_KIDS;
      var v = readInt(input); if (isNaN(v)) v = min;
      input.value = Math.min(max, Math.max(min, v + d)); render();
    });
  });
  [lessonsIn, kidsIn].forEach(function (input) {
    input.addEventListener("input", render);
    input.addEventListener("blur", function () {
      if (String(input.value).trim() === "") { input.value = input === lessonsIn ? DEFAULT_LESSONS : MIN_KIDS; render(); }
    });
  });
  [].forEach.call(box.querySelectorAll('input[name="kpp-pay"]'), function (r) { r.addEventListener("change", render); });
  render();
})(this);
